export type Person = {
  id: string;
  name: string;
};

export type ScheduleRow = {
  id: string;
  /** ISO date, format YYYY-MM-DD */
  date: string;
  imam: string;
  khatib: string;
  muadzin: string;
  note: string;
};

export type RotationMode = 'sequence' | 'random';

export type Settings = {
  /** bulan mulai, format YYYY-MM */
  start: string;
  months: number;
  mode: RotationMode;
  khatibSame: boolean;
  includeMuadzin: boolean;
  startIndex: number;
  /** saat true, jadwal dibuat/diperbarui otomatis mengikuti daftar petugas */
  autoSchedule: boolean;
};

export type AppState = {
  masjid: string;
  people: Person[];
  schedule: ScheduleRow[];
  settings: Settings;
  /** true bila jadwal terakhir dihasilkan otomatis (agar perubahan petugas ikut merapikan ulang) */
  autoGenerated?: boolean;
};