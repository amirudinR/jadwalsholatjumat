import type { Person, ScheduleRow, Settings, AppState, RotationMode } from '../types';

export const STORAGE_KEY = 'jadwal-jumat-v3';

const ALLOWED_MONTHS = [1, 2, 3, 6, 12];

export function uid(): string {
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}

export function defaultSettings(): Settings {
  return {
    start: '',
    startWeek: 1,
    months: 3,
    mode: 'sequence',
    khatibSame: true,
    includeMuadzin: true,
    startIndex: 0,
    autoSchedule: true,
  };
}

export function defaultState(): AppState {
  return { masjid: '', people: [], schedule: [], settings: defaultSettings() };
}

function normalizePeople(input: unknown): Person[] {
  if (!Array.isArray(input)) return [];
  const out: Person[] = [];
  for (const raw of input) {
    const name = raw && typeof raw === 'object'
      ? String((raw as Person).name ?? '').trim()
      : String(raw ?? '').trim();
    if (!name) continue;
    out.push({
      id: raw && typeof raw === 'object' && (raw as Person).id
        ? String((raw as Person).id)
        : uid(),
      name: name.slice(0, 60),
    });
  }
  return out;
}

function normalizeSchedule(input: unknown): ScheduleRow[] {
  if (!Array.isArray(input)) return [];
  const out: ScheduleRow[] = [];
  for (const raw of input) {
    if (!raw || typeof raw !== 'object') continue;
    const r = raw as Partial<ScheduleRow>;
    out.push({
      id: r.id ? String(r.id) : uid(),
      date: String(r.date ?? ''),
      imam: String(r.imam ?? ''),
      khatib: String(r.khatib ?? ''),
      muadzin: String(r.muadzin ?? ''),
      note: String(r.note ?? ''),
    });
  }
  return out;
}

function normalizeSettings(input: unknown): Settings {
  const base = defaultSettings();
  if (!input || typeof input !== 'object') return base;
  const s = input as Partial<Settings>;
  return {
    start: String(s.start ?? base.start),
    startWeek: Math.min(5, Math.max(1, Number(s.startWeek) || 1)),
    months: ALLOWED_MONTHS.includes(Number(s.months)) ? Number(s.months) : base.months,
    mode: s.mode === 'random' ? ('random' as RotationMode) : base.mode,
    khatibSame: s.khatibSame !== false,
    includeMuadzin: s.includeMuadzin !== false,
    startIndex: Math.max(0, Number(s.startIndex) || 0),
    autoSchedule: s.autoSchedule !== false,
  };
}

/** Bersihkan data mentah (dari localStorage maupun cloud) menjadi AppState valid. */
export function normalizeState(parsed: unknown): AppState {
  if (!parsed || typeof parsed !== 'object') return defaultState();
  const p = parsed as Partial<AppState>;
  return {
    masjid: String(p.masjid ?? '').slice(0, 70),
    people: normalizePeople(p.people),
    schedule: normalizeSchedule(p.schedule),
    settings: normalizeSettings(p.settings),
    autoGenerated: p.autoGenerated !== undefined ? p.autoGenerated === true : undefined,
  };
}

export function loadState(): AppState {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return defaultState();
    return normalizeState(JSON.parse(raw));
  } catch {
    return defaultState();
  }
}

export function saveState(state: AppState): boolean {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
    return true;
  } catch {
    return false;
  }
}
