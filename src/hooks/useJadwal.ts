import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import type { AppState, Person, ScheduleRow, Settings } from '../types';
import { loadState, saveState, uid } from '../lib/storage';
import { buildScheduleRows } from '../lib/schedule';
import { parseISO, toISO, toMonthValue, todayMidnight } from '../lib/date';

export type ToastKind = 'ok' | 'error' | 'info';
export type Toast = { id: number; text: string; kind: ToastKind };

export function useJadwal() {
  // Inisialisasi langsung dari localStorage (lazy initializer) agar tidak ada
  // jendela render "kosong" yang berisiko menimpa data tersimpan.
  const [state, setState] = useState<AppState>(() => {
    const loaded = loadState();
    if (loaded.settings.start) return loaded;
    return {
      ...loaded,
      settings: { ...loaded.settings, start: toMonthValue(new Date()) },
    };
  });
  const [toasts, setToasts] = useState<Toast[]>([]);
  const toastSeq = useRef(0);
  const firstCommit = useRef(true);
  // Ref ke state terbaru untuk dipakai di dalam callback (event handler).
  // Disinkronkan di dalam effect agar tidak mengakses ref saat render.
  const stateRef = useRef(state);
  useEffect(() => {
    stateRef.current = state;
  }, [state]);

  /* ---------------- toast ---------------- */
  const toast = useCallback((text: string, kind: ToastKind = 'info') => {
    const id = ++toastSeq.current;
    setToasts((prev) => [...prev, { id, text, kind }]);
    window.setTimeout(() => {
      setToasts((prev) => prev.filter((t) => t.id !== id));
    }, 2600);
  }, []);

  /* ---------------- persist ---------------- */
  useEffect(() => {
    if (firstCommit.current) {
      firstCommit.current = false;
      return;
    }
    if (!saveState(state)) {
      toast('Gagal menyimpan ke browser. Data bisa hilang setelah refresh.', 'error');
    }
  }, [state, toast]);

  /* ---------------- helpers ---------------- */
  const patch = useCallback((partial: Partial<AppState>) => {
    setState((prev) => ({ ...prev, ...partial }));
  }, []);

  const patchSettings = useCallback((partial: Partial<Settings>) => {
    setState((prev) => ({ ...prev, settings: { ...prev.settings, ...partial } }));
  }, []);

  const sortedSchedule = useMemo(() => {
    return [...state.schedule].sort((a, b) => {
      const da = parseISO(a.date);
      const db = parseISO(b.date);
      const ta = da ? da.getTime() : Number.POSITIVE_INFINITY;
      const tb = db ? db.getTime() : Number.POSITIVE_INFINITY;
      if (ta !== tb) return ta - tb;
      return a.id.localeCompare(b.id);
    });
  }, [state.schedule]);

  const nextRowId = useMemo(() => {
    const today = todayMidnight().getTime();
    for (const row of sortedSchedule) {
      const d = parseISO(row.date);
      if (d && d.getTime() >= today) return row.id;
    }
    return null;
  }, [sortedSchedule]);

  /* ---------------- auto-generate ---------------- */
  // Bila autoSchedule aktif dan jadwal dihasilkan otomatis, perbarui jadwal
  // mengikuti perubahan daftar petugas.
  const autoRefreshSchedule = useCallback((people: Person[]): AppState => {
    const s = stateRef.current;
    if (!s.settings.autoSchedule) return s;
    if (people.length === 0) return { ...s, people, schedule: [] };
    const rows = buildScheduleRows(people.map((p) => p.name), s.settings);
    return { ...s, people, schedule: rows, autoGenerated: true };
  }, []);

  /* ---------------- people ---------------- */
  const addPerson = useCallback((rawName: string) => {
    const name = rawName.trim();
    if (!name) return false;

    const s = stateRef.current;
    const exists = s.people.some((p) => p.name.toLowerCase() === name.toLowerCase());
    if (exists) {
      toast(`Nama "${name}" sudah ada.`, 'error');
      return false;
    }

    const person: Person = { id: uid(), name: name.slice(0, 60) };
    setState(autoRefreshSchedule([...s.people, person]));
    return true;
  }, [toast, autoRefreshSchedule]);

  const removePerson = useCallback((id: string) => {
    const s = stateRef.current;
    const people = s.people.filter((p) => p.id !== id);
    setState(autoRefreshSchedule(people));
  }, [autoRefreshSchedule]);

  const addManyPeople = useCallback((raw: string) => {
    const parts = raw.split(/[\n,;]+/).map((x) => x.trim()).filter(Boolean);
    if (parts.length === 0) return 0;

    const s = stateRef.current;
    const existing = new Set(s.people.map((p) => p.name.toLowerCase()));
    const fresh = parts.filter((name) => !existing.has(name.toLowerCase()));
    if (fresh.length === 0) {
      toast('Semua nama sudah terdaftar.', 'error');
      return 0;
    }

    const people = [
      ...s.people,
      ...fresh.map((name): Person => ({ id: uid(), name: name.slice(0, 60) })),
    ];
    setState(autoRefreshSchedule(people));
    toast(`${fresh.length} nama ditambahkan.`, 'ok');
    return fresh.length;
  }, [toast, autoRefreshSchedule]);

  /* ---------------- schedule ---------------- */
  const generateSchedule = useCallback(() => {
    const s = stateRef.current;
    const names = s.people.map((p) => p.name);
    if (names.length === 0) {
      toast('Isi daftar petugas terlebih dahulu.', 'error');
      return false;
    }

    const rows = buildScheduleRows(names, s.settings);
    if (rows.length === 0) {
      toast('Rentang bulan tidak valid.', 'error');
      return false;
    }

    setState({ ...s, schedule: rows, autoGenerated: false });
    toast(`Berhasil membuat ${rows.length} jadwal untuk ${names.length} petugas.`, 'ok');
    return true;
  }, [toast]);

  const addRow = useCallback(() => {
    const s = stateRef.current;
    const last = s.schedule[s.schedule.length - 1];
    const base = last ? parseISO(last.date) : new Date();
    const d = base ? new Date(base.getTime()) : new Date();
    d.setDate(d.getDate() + 7);
    const row: ScheduleRow = { id: uid(), date: toISO(d), imam: '', khatib: '', muadzin: '', note: '' };
    setState({ ...s, schedule: [...s.schedule, row], autoGenerated: false });
  }, []);

  const updateRow = useCallback((id: string, patchRow: Partial<ScheduleRow>) => {
    const s = stateRef.current;
    setState({
      ...s,
      schedule: s.schedule.map((r) => (r.id === id ? { ...r, ...patchRow } : r)),
      autoGenerated: false,
    });
  }, []);

  const removeRow = useCallback((id: string) => {
    const s = stateRef.current;
    setState({
      ...s,
      schedule: s.schedule.filter((r) => r.id !== id),
      autoGenerated: s.settings.autoSchedule ? (s.autoGenerated ?? true) : false,
    });
  }, []);

  const clearSchedule = useCallback(() => {
    const s = stateRef.current;
    setState({ ...s, schedule: [] });
  }, []);

  return {
    state,
    patch,
    patchSettings,
    sortedSchedule,
    nextRowId,
    people: state.people,
    toasts,
    toast,
    addPerson,
    addManyPeople,
    removePerson,
    generateSchedule,
    addRow,
    updateRow,
    removeRow,
    clearSchedule,
  };
}